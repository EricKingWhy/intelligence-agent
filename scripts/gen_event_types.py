"""事件词汇单一来源生成器（Phase 9 技术债修复）。

src/agent_harness/session/event.py 是事件词汇唯一真值；本脚本从它生成
web/src/generated/event-types.ts，前端 types.ts re-export 该产物。
此前前后端双处手工维护，因漂移出过 bug（tool/started vs tool/call）。

#1498（G-1）：同一份词汇再生成一份 TUI 产物 tui/src/generated/event-types.ts。
TUI 的 `tui/tsconfig.json` 是 `rootDir: "."`，跨包 import web 产物会撞
TS6059（且无 package.json 的目录在 verbatimModuleSyntax 下算 CommonJS，
另报 TS1287），所以产物必须落在 tui 包内——但仍由**本脚本**从 event.py 生成，
词汇权威只有一处（不新建第二套词汇表）。
两份产物内容只有文件头那一行破折号不同：TUI 侧注释里禁用非 GBK 安全字符
（U+2014 会被 `tui/test/glyphs.test.ts` 判红），故用 ASCII 连字符。

用法：
    uv run python scripts/gen_event_types.py

产物 commit 进仓库，前端构建保持纯 Node；漂移由
tests/test_event_types_generated.py 兜底（失败时提示运行上面的命令）。
"""

from __future__ import annotations

import re
from pathlib import Path

import agent_harness.session.event as event_module

ROOT = Path(__file__).resolve().parent.parent
OUTPUT_PATH = ROOT / "web" / "src" / "generated" / "event-types.ts"
#: #1498：TUI 侧产物（落在 tui 包内，`rootDir: "."` 才成立）。
TUI_OUTPUT_PATH = ROOT / "tui" / "src" / "generated" / "event-types.ts"

#: 产物文件头。两份只有破折号/符号不同：TUI 侧注释也受
#: `tui/test/glyphs.test.ts` 的 GBK 白名单管（U+2014 / U+2260 都会判红），故用 ASCII。
_WEB_HEADER = "// GENERATED by scripts/gen_event_types.py — DO NOT EDIT BY HAND."
_TUI_HEADER = "// GENERATED by scripts/gen_event_types.py - DO NOT EDIT BY HAND."
_WEB_STREAM_DOC = (
    "/** Ephemeral streaming signals — never persisted (invariant #4: Event ≠ Diagnostic Log). */"
)
_TUI_STREAM_DOC = (
    "/** Ephemeral streaming signals - never persisted (invariant #4: Event != Diagnostic Log). */"
)

# 事件值形状：`域/子域[/细分]`，如 tool/call、model/delta、operation/reconcile-required。
# event.py 里所有匹配此形状的模块级字符串常量都视为事件词汇；
# 将来若新增同形状的非事件字符串常量，本脚本与守卫测试会暴露它。
# #1193：形状放宽为「裸小写词 或 域/子域」——票面 schema 指定的 error 事件
# wire type 是裸词 "error"（见 event.py 的 ERROR 注释）。两向守卫语义不变：
# 匹配到的常量必须入册（unregistered），入册值必须有常量（orphan）。
_EVENT_VALUE_RE = re.compile(r"^[a-z]+(/[a-z_-]+)*$")


def collect_vocabulary() -> tuple[list[tuple[str, str]], frozenset[str], frozenset[str]]:
    """收集事件词汇：(常量名, 值) 列表（按 event.py 定义序）+ 持久集 + 流式集。"""
    pairs = [
        (name, value)
        for name, value in vars(event_module).items()
        if not name.startswith("_")
        and isinstance(value, str)
        and _EVENT_VALUE_RE.match(value)
    ]
    return pairs, event_module.EVENT_TYPES, event_module.STREAM_ONLY_TYPES


def _render(header: str, stream_doc: str) -> str:
    """渲染产物正文（纯函数；两份产物只差文件头的符号，正文逐字相同）。"""
    pairs, persistent, stream_only = collect_vocabulary()

    values = {value for _, value in pairs}
    orphans = (persistent | stream_only) - values
    if orphans:
        raise ValueError(
            f"EVENT_TYPES/STREAM_ONLY_TYPES 含没有对应模块常量的孤儿值: {sorted(orphans)}"
        )
    unregistered = values - (persistent | stream_only)
    if unregistered:
        raise ValueError(
            f"event.py 中的事件常量未入册 EVENT_TYPES/STREAM_ONLY_TYPES: {sorted(unregistered)}"
        )

    lines = [
        header,
        "// Source of truth: src/agent_harness/session/event.py",
        "// Regenerate: uv run python scripts/gen_event_types.py",
        "",
        "/** All event type constants (durable + stream-only), mirroring event.py. */",
        "export const EventType = {",
    ]
    lines.extend(f"  {name}: '{value}'," for name, value in pairs)
    lines.extend(
        [
            "} as const;",
            "",
            "export type EventTypeValue = (typeof EventType)[keyof typeof EventType];",
            "",
            stream_doc,
            "export const STREAM_ONLY_TYPES = [",
        ]
    )
    lines.extend(f"  '{value}'," for value in sorted(stream_only))
    lines.extend(["] as const;", ""])

    return "\n".join(lines)


def generate_ts() -> str:
    """渲染 web/src/generated/event-types.ts 内容（纯函数，供 CLI 与守卫测试共用）。"""
    return _render(_WEB_HEADER, _WEB_STREAM_DOC)


def generate_tui_ts() -> str:
    """渲染 tui/src/generated/event-types.ts 内容（同一份词汇，GBK 安全注释）。"""
    return _render(_TUI_HEADER, _TUI_STREAM_DOC)


def main() -> None:
    for path, content in (
        (OUTPUT_PATH, generate_ts()),
        (TUI_OUTPUT_PATH, generate_tui_ts()),
    ):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
